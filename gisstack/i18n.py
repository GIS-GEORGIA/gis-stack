_GEO = "Ⴀ-ჿ"
_compiled: tuple[re.Pattern[str], dict[str, str]] | None = None


def _table() -> tuple[re.Pattern[str], dict[str, str]]:
    global _compiled
    if _compiled is None:
        keys = sorted(EN, key=len, reverse=True)          # longest first: whole phrases beat their own fragments
        rx = re.compile(f"(?<![{_GEO}])(?:" + "|".join(re.escape(k) for k in keys) + f")(?![{_GEO}])")
        _compiled = (rx, EN)
    return _compiled


def has_georgian(s: str) -> bool:
    return re.search(f"[{_GEO}]", s) is not None


def tr(text: str, lang: str = "en") -> str:
    """Translate a UI string.  lang='ka' (or anything but 'en') returns it unchanged."""
    if lang != "en" or not text or not has_georgian(text):
        return text
    rx, table = _table()
    whole = table.get(text.strip())
    if whole is not None:
        lead = text[: len(text) - len(text.lstrip())]
        tail = text[len(text.rstrip()):]
        return lead + whole + tail
    return rx.sub(lambda m: table[m.group(0)], text)


def untranslated(text: str) -> str:
    """Georgian left over after translating (empty = fully translated)."""
    return "".join(re.findall(f"[{_GEO}]+", tr(text, "en")))

